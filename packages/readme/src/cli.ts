/**
 * README generator CLI.
 *
 *   build [outDir]   write README.md and readme/*.svg (default outDir: readme-out/), and the
 *                    Worker's font module for its live README cards
 *
 * Reads the same profile as packages/profile (see find.ts) and only ever renders its PUBLIC
 * projection. Needs apps/web/src/generated/stack-logos.json, so run after `npm run logos:build`.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { loadProfile, projectFor, ProfileError } from "@dan-town/profile";
import { resolveProfilePath, root } from "@dan-town/profile/find";
import { loadFonts } from "./fonts.ts";
import { DIR, renderReadme } from "./readme.ts";

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function main() {
  const [cmd = "build", arg = "readme-out"] = process.argv.slice(2);
  if (cmd !== "build") throw new ProfileError(`unknown command "${cmd}" (expected build)`);

  const profile = projectFor(loadProfile(readFileSync(resolveProfilePath(), "utf8")), "public");
  const logosPath = join(root, "apps/web/src/generated/stack-logos.json");
  if (!existsSync(logosPath)) throw new ProfileError("stack-logos.json is missing: run `npm run logos:build` first");
  const pixelated = JSON.parse(readFileSync(logosPath, "utf8")) as Record<string, { hex: string; rows: string[] }>;
  const fonts = loadFonts();

  const out = resolve(root, arg);
  rmSync(join(out, DIR), { recursive: true, force: true });
  const files = renderReadme({ profile, fonts, pixelated });
  for (const [name, content] of files) write(join(out, name), content);
  const kb = [...files.values()].reduce((n, f) => n + f.length, 0) / 1024;
  console.log(`✓ README: ${files.size} files (${kb.toFixed(0)} KB) in ${out.replace(root, ".")}`);

  // The Worker can't read node_modules at runtime, so its live cards get the fonts as a module.
  write(
    join(root, "workers/api/src/generated/readme-fonts.ts"),
    `// Generated by packages/readme. Do not edit.\nimport type { FontData } from "../../../../packages/readme/src/svg.ts";\n` +
      `export const README_FONTS: FontData = ${JSON.stringify(fonts)};\n`,
  );
}

try {
  main();
} catch (err) {
  console.error(err instanceof ProfileError ? `✗ ${err.message}` : err);
  process.exit(1);
}

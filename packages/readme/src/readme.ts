/**
 * The GitHub profile README (github.com/dannguyen111), generated from the PUBLIC projection of the
 * canonical profile. Every card is an SVG in two themes, swapped by GitHub's light/dark mode via
 * <picture>, and styled like the town (light) or the Dev Center's mission control (dark).
 *
 * renderReadme() returns every file to write: README.md plus readme/*.svg.
 */
import type { Profile } from "@dan-town/profile/schema";
import { LOADOUT, PINNED } from "../../../apps/web/src/lib/board.ts";
import { pickLogo } from "../../../apps/web/src/lib/stack-meta.ts";
import { renderBanner } from "./banner.ts";
import { buildHeight, renderAchievements, renderBuild, renderButton, renderNow, renderStack, renderTyping } from "./cards.ts";
import { doc, esc, FAMILY, type FontData } from "./svg.ts";
import { THEMES, type Mode } from "./theme.ts";

export const SITE = "https://si-dan.com";
/** Where the generated SVGs live in the README repo. */
export const DIR = "readme";

export interface ReadmeInput {
  /** Must already be projectFor(profile, "public"). */
  profile: Profile;
  fonts: FontData;
  /** stack-logos.json: { [tech]: { hex, rows } }. */
  pixelated: Record<string, { hex: string; rows: string[] }>;
}

const MODES: Mode[] = ["light", "dark"];

/** "B.S. in Computer Science and Mathematics" → "CS + Math · Rank 7/547 · Class of 2026", as on the board. */
export function credits(p: Profile): string {
  const edu = p.education[0];
  if (!edu) return p.identity.tagline;
  const major = edu.degree.replace(/^.*? in /, "").replace("Computer Science", "CS").replace(" and ", " + ").replace("Mathematics", "Math");
  return [major, edu.rank && `Rank ${edu.rank}`, edu.end && `Class of ${edu.end.slice(0, 4)}`].filter(Boolean).join(" · ");
}

/** A light/dark pair as a <picture>, optionally linked. */
function picture(name: string, alt: string, { href, width }: { href?: string; width?: number } = {}): string {
  const img =
    `<picture><source media="(prefers-color-scheme: dark)" srcset="${DIR}/${name}-dark.svg">` +
    `<img alt="${esc(alt)}" src="${DIR}/${name}-light.svg"${width ? ` width="${width}"` : ""}></picture>`;
  return href ? `<a href="${href}">${img}</a>` : img;
}

/** The same, for images hosted elsewhere (the live Spotify card, the activity widgets). */
function remotePicture(light: string, dark: string, alt: string, href?: string): string {
  const img = `<picture><source media="(prefers-color-scheme: dark)" srcset="${dark}"><img alt="${esc(alt)}" src="${light}"></picture>`;
  return href ? `<a href="${href}">${img}</a>` : img;
}

const LINK_ICONS: Record<string, string> = { github: "GITHUB", linkedin: "LINKEDIN", email: "EMAIL", depop: "DEPOP" };

export function renderReadme({ profile: p, fonts, pixelated }: ReadmeInput): Map<string, string> {
  const files = new Map<string, string>();
  const put = (name: string, render: (mode: Mode) => string) => {
    for (const mode of MODES) files.set(`${DIR}/${name}-${mode}.svg`, render(mode));
  };
  const ctx = (mode: Mode) => ({ theme: THEMES[mode], fonts, logo: (tech: string) => pickLogo(tech, pixelated) });
  const user = p.integrations.github.username;
  const id = p.identity;

  put("banner", (m) => renderBanner({ name: id.name, headline: id.headline, credits: credits(p) }, m, fonts));
  const phrases = [id.headline, id.tagline, ...(id.open_to ? [`Open to: ${id.open_to}`] : [])];
  put("typing", (m) => renderTyping(phrases, ctx(m)));
  const hasNow = renderNow(p, ctx("light")) !== null;
  if (hasNow) put("now", (m) => renderNow(p, ctx(m))!);

  const builds = PINNED.flatMap((pid) => p.projects.filter((x) => x.id === pid));
  const bh = builds.length ? buildHeight(builds) : 0;
  builds.forEach((b, i) => put(`build-${b.id}`, (m) => renderBuild(b, bh, i, ctx(m))));

  if (p.skills.length) put("stack", (m) => renderStack(p, ctx(m)));
  if (p.honors.length) put("achievements", (m) => renderAchievements(p, ctx(m)));

  const links = p.links.filter((l) => l.url);
  links.forEach((l) => put(`link-${l.id}`, (m) => renderButton(LINK_ICONS[l.id] ?? l.label.toUpperCase(), ctx(m))));
  put("visit", (m) => renderButton("VISIT THE TOWN  >  SI-DAN.COM", ctx(m), { primary: true, size: 12 }));
  for (const [name, label] of [["h-builds", "FEATURED BUILDS"], ["h-radio", "ON REPEAT"], ["h-activity", "TOWN ACTIVITY"], ["h-hi", "SAY HI"]] as const)
    put(name, (m) => heading(label, m, fonts));

  // ── README.md ──
  const toolbelt = LOADOUT.filter((s) => p.skills.some((g) => g.items.includes(s)));
  const md: string[] = [];
  md.push(
    `<!--\n  Generated by dan-town/packages/readme from the canonical profile (dan-profile/profile.yaml).\n` +
      `  Do not edit by hand: it is rebuilt and pushed by dan-town's CI whenever the profile changes.\n-->`,
  );
  md.push(
    `<div align="center">\n\n${picture("banner", `${id.name}: ${id.headline}. ${credits(p)}`, { href: SITE })}\n\n` +
      `${picture("typing", phrases.join(" · "))}\n\n</div>`,
  );
  // A plain-text intro, for screen readers, search, and anyone with images off.
  md.push(`<p align="center"><b>${esc(id.tagline)}</b><br><sub>${esc(p.about.intro)}</sub></p>`);
  if (hasNow) {
    const cur = p.experience.find((e) => e.end === null);
    md.push(picture("now", [cur && `Now: ${cur.role} @ ${cur.org}`, id.open_to && `Open to: ${id.open_to}`].filter(Boolean).join(". ")));
  }
  if (builds.length) {
    md.push(picture("h-builds", "Featured builds"));
    md.push(
      `<p>${builds.map((b) => picture(`build-${b.id}`, `${b.title}: ${b.tagline} (${b.tags.join(", ")})`, { href: `${SITE}/projects/${b.id}` })).join("")}</p>`,
    );
    md.push(`<p align="right"><a href="${SITE}/dev"><sub>All projects at the Dev Center →</sub></a></p>`);
  }
  if (p.skills.length) md.push(picture("stack", `Toolbelt: ${toolbelt.join(", ")}, and more`, { href: `${SITE}/dev` }));
  if (p.honors.length) md.push(picture("achievements", `Achievements: ${p.honors.slice(0, 5).map((h) => h.title).join(", ")}`, { href: `${SITE}/about` }));

  if (p.integrations.spotify.enabled) {
    md.push(picture("h-radio", "On repeat"));
    md.push(
      remotePicture(
        `${SITE}/api/readme/on-repeat.svg?theme=light`,
        `${SITE}/api/readme/on-repeat.svg?theme=dark`,
        "What Dan has on repeat on Spotify",
        `${SITE}/music`,
      ),
    );
  }
  if (user) {
    const raw = (f: string) => `https://raw.githubusercontent.com/${user}/${user}/output/${f}`;
    md.push(picture("h-activity", "Town activity"));
    md.push(remotePicture(raw("profile-3d-light.svg"), raw("profile-3d-dark.svg"), `${user}'s contributions as an isometric city`));
    md.push(remotePicture(raw("snake-light.svg"), raw("snake-dark.svg"), `A snake eating ${user}'s contribution graph`));
  }

  md.push(picture("h-hi", "Say hi"));
  md.push(
    `<p align="center">\n${links.map((l) => picture(`link-${l.id}`, l.label, { href: l.url! })).join("\n")}\n</p>\n\n` +
      `<p align="center">${picture("visit", `Visit the town at si-dan.com`, { href: SITE })}</p>`,
  );
  md.push(
    `<p align="center"><sub>🏡 This README is drawn from the same profile as <a href="${SITE}">my pixel town</a>, ` +
      `and redraws itself whenever I update it.</sub></p>`,
  );
  files.set("README.md", md.join("\n\n") + "\n");
  return files;
}

/** A section heading: a wooden plank (town) or a bracketed console label (mission control) on a rule. */
function heading(label: string, mode: Mode, fonts: FontData): string {
  const t = THEMES[mode];
  const light = mode === "light";
  const full = `${t.labelPrefix}${label}`;
  const lw = full.length * 12 + 28;
  const body =
    `<g shape-rendering="crispEdges">` +
    `<rect x="0" y="16" width="830" height="2" fill="${light ? "#ead9c2" : "#26325c"}"/>` +
    (light ? `<rect x="3" y="7" width="${lw}" height="26" fill="#6b4226"/>` : "") +
    `<rect x="0.5" y="4.5" width="${lw - 1}" height="25" fill="${light ? "#8a5a34" : "#0b1020"}" stroke="${light ? "#6b4226" : t.label}"/>` +
    `</g>` +
    `<text x="14" y="23" font-family="${FAMILY.retro}" font-size="12" fill="${light ? "#fff8ee" : t.label}">${esc(full)}</text>`;
  return doc(830, 36, body, { fonts: ["retro"], data: fonts, title: label });
}
